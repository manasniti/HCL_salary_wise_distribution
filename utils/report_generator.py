_HDR_FILL = PatternFill("solid", fgColor="0B1426")
_HDR_FONT = Font(bold=True, color="FFFFFF")
_THIN = Side(style="thin", color="CBD5E1")


def to_excel(report: Report) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Summary"
    ws["A1"] = f"{settings.app_name} — {report.title}"
    ws["A1"].font = Font(bold=True, size=16, color="0B1426")
    ws["A2"] = report.subtitle
    ws["A2"].font = Font(italic=True, color="475569")
    row = 4
    for k, v in report.meta.items():
        ws.cell(row=row, column=1, value=k).font = Font(bold=True)
        ws.cell(row=row, column=2, value=neutralise_formula(v))
        row += 1
    row += 1
    if report.kpis:
        ws.cell(row=row, column=1, value="Key figures").font = Font(bold=True, size=12, color="0891B2")
        row += 1
        for k, v in report.kpis.items():
            ws.cell(row=row, column=1, value=k)
            ws.cell(row=row, column=2, value=neutralise_formula(v)).font = Font(bold=True)
            row += 1
    for note in report.notes:
        row += 1
        ws.cell(row=row, column=1, value=neutralise_formula(note)).font = Font(italic=True, color="475569")
    ws.cell(row=row + 2, column=1, value="Confidential — internal use only.").font = Font(italic=True, color="B91C1C")
    ws.column_dimensions["A"].width = 28
    ws.column_dimensions["B"].width = 48

    used = set()
    for name, df in report.tables:
        sheet = name[:31]
        while sheet in used:
            sheet = sheet[:28] + f"_{len(used)}"
        used.add(sheet)
        _write_sheet(wb.create_sheet(sheet), df, report)

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def _write_sheet(ws, df: pd.DataFrame, report: Report) -> None:
    money_fmt = f'"{settings.currency_symbol}"#,##0.00'
    for j, col in enumerate(df.columns, start=1):
        c = ws.cell(row=1, column=j, value=str(col))
        c.fill, c.font = _HDR_FILL, _HDR_FONT
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = Border(bottom=_THIN)
    for i, rec in enumerate(df.itertuples(index=False), start=2):
        for j, (col, val) in enumerate(zip(df.columns, rec), start=1):
            if val is not None and not isinstance(val, str) and pd.isna(val):
                val = None
            elif hasattr(val, "item") and not isinstance(val, str):
                val = val.item()
            cell = ws.cell(row=i, column=j, value=neutralise_formula(val))
            if col in report.money_columns and isinstance(val, (int, float)):
                cell.number_format = money_fmt
            elif col in report.pct_columns and isinstance(val, (int, float)):
                cell.number_format = '0.00"%"'
            elif hasattr(val, "year"):
                cell.number_format = "dd-mmm-yyyy"
            cell.border = Border(bottom=_THIN)
    for j, col in enumerate(df.columns, start=1):
        sample = [len(str(col))] + [len(f"{v:,.2f}" if isinstance(v, float) else str(v)) for v in df[col].head(500)]
        ws.column_dimensions[get_column_letter(j)].width = min(max(sample) + 4, 45)
    ws.freeze_panes = "A2"
    if len(df):
        ws.auto_filter.ref = f"A1:{get_column_letter(len(df.columns))}{len(df) + 1}"


