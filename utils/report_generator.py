def _fmt_cell(col: str, v: Any, report: Report) -> str:
    if v is None or (not isinstance(v, str) and pd.isna(v)):
        return "—"
    if col in report.money_columns and isinstance(v, (int, float)):
        return f"{PDF_CURRENCY}{v:,.0f}"
    if col in report.pct_columns and isinstance(v, (int, float)):
        return f"{v:,.2f}%"
    if isinstance(v, float):
        return f"{v:,.2f}"
    if hasattr(v, "strftime"):
        return v.strftime("%d %b %Y")
    if isinstance(v, str):
        return v.replace("₹", PDF_CURRENCY)
    return f"{v:,}" if isinstance(v, int) else str(v)


def to_pdf(report: Report) -> bytes:
    buf = io.BytesIO()
    page = landscape(A4)
    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=14 * mm, rightMargin=14 * mm,
                            topMargin=20 * mm, bottomMargin=16 * mm, title=report.title,
                            author=settings.app_name, subject=report.subtitle)
    ss = getSampleStyleSheet()
    h1 = ParagraphStyle("h1", parent=ss["Title"], alignment=TA_LEFT, textColor=NAVY, fontSize=20, spaceAfter=2)
    sub = ParagraphStyle("sub", parent=ss["Normal"], textColor=SLATE, fontSize=10, spaceAfter=8)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], textColor=CYAN, fontSize=13, spaceBefore=10, spaceAfter=6)
    small = ParagraphStyle("small", parent=ss["Normal"], fontSize=8.5, textColor=SLATE)
    cell_style = ParagraphStyle("cell", parent=ss["Normal"], fontSize=7.5, leading=9)
    head_style = ParagraphStyle("head", parent=cell_style, textColor=colors.white, fontName="Helvetica-Bold")

    def esc(s: str) -> str:
        return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    story: list = [Paragraph(esc(report.title), h1), Paragraph(esc(report.subtitle), sub)]
    meta_rows = [[Paragraph(f"<b>{esc(k)}</b>", small), Paragraph(esc(_fmt_cell("", v, report)), small)]
                 for k, v in report.meta.items()]
    story.append(Table(meta_rows, colWidths=[55 * mm, 150 * mm], hAlign="LEFT"))
    story.append(Spacer(1, 6))

    if report.kpis:
        kp = [[Paragraph(f"<font size=8 color='#475569'>{esc(k).upper()}</font><br/>"
                         f"<font size=13><b>{esc(_fmt_cell('', v, report))}</b></font>", ss["Normal"])
               for k, v in report.kpis.items()]]
        t = Table(kp, colWidths=[(page[0] - 28 * mm) / len(report.kpis)] * len(report.kpis))
        t.setStyle(TableStyle([
            ("BOX", (0, 0), (-1, -1), 0.6, CYAN), ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#cbd5e1")),
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f0fdff")),
            ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
        ]))
        story += [t, Spacer(1, 6)]

    for note in report.notes:
        story.append(Paragraph(esc(note), small))

    if report.bar_chart is not None:
        title, series = report.bar_chart
        story.append(KeepTogether([Paragraph(esc(title), h2), _bar_drawing(series, page[0] - 28 * mm)]))

    avail = page[0] - 28 * mm
    for i, (name, df) in enumerate(report.tables):
        if i > 0 or report.bar_chart is not None:
            story.append(PageBreak())
        story.append(Paragraph(esc(name), h2))
        if df.empty:
            story.append(Paragraph("No records.", small))
            continue
        cols = list(df.columns)
        data = [[Paragraph(esc(c), head_style) for c in cols]]
        for rec in df.itertuples(index=False):
            data.append([Paragraph(esc(_fmt_cell(c, v, report)), cell_style) for c, v in zip(cols, rec)])
        widths = _col_widths(df, avail)
        t = Table(data, colWidths=widths, repeatRows=1)
        style = [
            ("BACKGROUND", (0, 0), (-1, 0), NAVY),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
            ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]
        for r in range(1, len(data)):
            if r % 2 == 0:
                style.append(("BACKGROUND", (0, r), (-1, r), ZEBRA))
        if str(df.iloc[-1, 0]).upper() == "TOTAL":
            style += [("BACKGROUND", (0, len(data) - 1), (-1, len(data) - 1), colors.HexColor("#e0f2fe")),
                      ("LINEABOVE", (0, len(data) - 1), (-1, len(data) - 1), 1, CYAN)]
        t.setStyle(TableStyle(style))
        story.append(t)

    def decorate(canvas, doc_):
        canvas.saveState()
        w, h = page
        canvas.setFillColor(NAVY)
        canvas.rect(0, h - 12 * mm, w, 12 * mm, fill=1, stroke=0)
        canvas.setFillColor(colors.HexColor("#22d3ee"))
        canvas.rect(0, h - 12.6 * mm, w, 0.6 * mm, fill=1, stroke=0)
        canvas.setFillColor(colors.white)
        canvas.setFont("Helvetica-Bold", 10)
        canvas.drawString(14 * mm, h - 7.8 * mm, settings.app_name.upper())
        canvas.setFont("Helvetica", 8.5)
        canvas.drawRightString(w - 14 * mm, h - 7.8 * mm, settings.organisation_name)
        canvas.setFillColor(SLATE)
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(14 * mm, 8 * mm, "Confidential — internal use only. Generated from verified database records.")
        canvas.drawRightString(w - 14 * mm, 8 * mm, f"Page {doc_.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue()


def _col_widths(df: pd.DataFrame, avail: float) -> list[float]:
    weights = []
    for c in df.columns:
        sample = df[c].head(200).astype(str).str.len()
        weights.append(max(len(str(c)) * 0.8, float(sample.quantile(0.9)) if len(sample) else 6, 5))
    total = sum(weights)
    return [avail * w / total for w in weights]


def _bar_drawing(series: pd.Series, width: float) -> Drawing:
    n = len(series)
    height = max(120, 18 * n + 40)
    d = Drawing(width, height)
    chart = HorizontalBarChart()
    chart.x, chart.y = 140, 20
    chart.width, chart.height = width - 200, height - 40
    chart.data = [list(series.values.astype(float))]
    chart.categoryAxis.categoryNames = [str(s)[:28] for s in series.index]
    chart.categoryAxis.labels.fontSize = 7.5
    chart.categoryAxis.labels.fontName = "Helvetica"
    chart.valueAxis.labels.fontName = "Helvetica"
    chart.categoryAxis.labels.boxAnchor = "e"
    chart.valueAxis.valueMin = 0
    chart.valueAxis.labels.fontSize = 7
    chart.valueAxis.labelTextFormat = lambda v: f"{v / 1e5:,.1f}L" if settings.currency_symbol == "₹" else f"{v / 1e3:,.0f}K"
    chart.bars[0].fillColor = colors.HexColor("#0891b2")
    chart.bars[0].strokeColor = None
    chart.barSpacing = 2
    d.add(chart)
    d.add(String(width - 50, 4, PDF_CURRENCY.strip(), fontSize=7, fillColor=SLATE))
    return d
