NAVY = colors.HexColor("#0b1426")
CYAN = colors.HexColor("#0891b2")
SLATE = colors.HexColor("#475569")
ZEBRA = colors.HexColor("#f1f5f9")

# PDF uses a "Rs." / ISO prefix because the built-in Type-1 fonts lack the ₹ glyph.
PDF_CURRENCY = {"₹": "INR ", "€": "EUR ", "£": "GBP "}.get(settings.currency_symbol, settings.currency_symbol)


@dataclass
class Report:
    title: str
    subtitle: str
    meta: dict[str, str]
    kpis: dict[str, str] = field(default_factory=dict)
    tables: list[tuple[str, pd.DataFrame]] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)
    money_columns: set[str] = field(default_factory=set)
    pct_columns: set[str] = field(default_factory=set)
    bar_chart: tuple[str, pd.Series] | None = None  # (title, Series indexed by label)


# --------------------------------------------------------------------------
# Report content builders
# --------------------------------------------------------------------------
def _meta(user: dict, statuses: tuple[str, ...]) -> dict[str, str]:
    return {
        "Generated at": datetime.now().strftime("%d %b %Y, %H:%M"),
        "Generated by": f"{user['full_name']} ({user['role']})",
        "Employment status filter": ", ".join(statuses) if statuses else "All statuses",
        "Source": "PostgreSQL – verified records only",
    }


def _m(v: float | None) -> str:
    return "—" if v is None or pd.isna(v) else f"{settings.currency_symbol}{v:,.0f}"


def department_report(user: dict, statuses: tuple[str, ...]) -> Report | None:
    summary = an.department_summary(statuses)
    if summary.empty:
        return None
    k = an.kpis(statuses)
    table = summary.rename(columns={
        "department": "Department", "employee_count": "Employees", "total_monthly_salary": "Total Monthly",
        "average_salary": "Average", "minimum_salary": "Minimum", "maximum_salary": "Maximum",
        "annual_salary_expenditure": "Annual Expenditure", "salary_contribution_pct": "Contribution %",
    })
    total_row = pd.DataFrame([{
        "Department": "TOTAL", "Employees": table["Employees"].sum(), "Total Monthly": table["Total Monthly"].sum(),
        "Average": k["average_salary"], "Minimum": k["lowest_salary"], "Maximum": k["highest_salary"],
        "Annual Expenditure": table["Annual Expenditure"].sum(), "Contribution %": 100.0,
    }])
    table = pd.concat([table, total_row], ignore_index=True)
    return Report(
        title="Department Salary Report",
        subtitle="Department-wise salary distribution",
        meta=_meta(user, statuses),
        kpis={
            "Employees": f"{k['total_employees']:,}", "Departments": f"{k['total_departments']:,}",
            "Monthly payroll": _m(k["total_monthly_salary"]), "Annual payroll": _m(k["total_monthly_salary"] * 12),
            "Average salary": _m(k["average_salary"]),
        },
        tables=[("Department summary", table)],
        money_columns={"Total Monthly", "Average", "Minimum", "Maximum", "Annual Expenditure"},
        pct_columns={"Contribution %"},
        bar_chart=("Monthly payroll by department",
                   summary.set_index("department")["total_monthly_salary"].sort_values()),
    )


def employee_summary_report(user: dict, statuses: tuple[str, ...], can_see_pii: bool) -> Report | None:
    df = an.employees_export(statuses=statuses, sort_by="Department")
    if df.empty:
        return None
    if not can_see_pii:
        df["Employee Name"] = [mask_name(n, c) for n, c in zip(df["Employee Name"], df["Employee ID"])]
    notes = [] if can_see_pii else ["Employee names are pseudonymised for your role."]
    k = an.kpis(statuses)
    return Report(
        title="Employee Salary Summary",
        subtitle="Per-employee salary listing",
        meta=_meta(user, statuses),
        kpis={"Employees": f"{len(df):,}", "Monthly payroll": _m(df["Monthly Salary"].sum()),
              "Average": _m(k["average_salary"]), "Median": _m(df["Monthly Salary"].median())},
        tables=[("Employees", df)],
        notes=notes,
        money_columns={"Monthly Salary", "Annual Salary"},
    )


def monthly_expenditure_report(user: dict) -> Report | None:
    monthly = an.monthly_expenditure()
    if monthly.empty:
        return None
    t = monthly.copy()
    t["pay_period"] = t["pay_period"].dt.strftime("%b %Y")
    t = t.rename(columns={"pay_period": "Pay Period", "paid_employees": "Employees Paid",
                          "total_salary": "Total Salary", "average_salary": "Average Salary",
                          "mom_change_pct": "MoM Change %"})
    dept = an.department_trend()
    pivot = dept.pivot_table(index="department", columns="pay_period", values="total_salary", aggfunc="sum")
    pivot.columns = [c.strftime("%b %Y") for c in pivot.columns]
    pivot = pivot.reset_index().rename(columns={"department": "Department"})
    meta = _meta(user, ())
    meta["Employment status filter"] = "Not applicable (historical payroll)"
    return Report(
        title="Monthly Expenditure Report",
        subtitle="Payroll expenditure by pay period",
        meta=meta,
        kpis={"Pay periods": f"{len(monthly):,}", "Cumulative payroll": _m(monthly["total_salary"].sum()),
              "Latest month": _m(monthly["total_salary"].iloc[-1]),
              "Monthly average": _m(monthly["total_salary"].mean())},
        tables=[("Payroll by month", t), ("Department × month", pivot)],
        money_columns={"Total Salary", "Average Salary", *[c for c in pivot.columns if c != "Department"]},
        pct_columns={"MoM Change %"},
    )


def eda_report(user: dict, statuses: tuple[str, ...]) -> Report | None:
    df = an.employee_frame(statuses)
    if df.empty:
        return None
    st_ = an.descriptive_stats(df["monthly_salary"])
    outliers, lo, hi = an.iqr_outliers(df)
    stats_table = pd.DataFrame([
        ("Count", f"{st_['count']:,}"), ("Mean", _m(st_["mean"])), ("Median", _m(st_["median"])),
        ("Mode", f"{_m(st_['mode'])} (×{st_['mode_count']})"), ("Standard deviation", _m(st_["std"])),
        ("Variance", f"{st_['variance']:,.0f}"), ("Minimum", _m(st_["min"])), ("Q1 (25%)", _m(st_["q1"])),
        ("Q2 (50%)", _m(st_["q2"])), ("Q3 (75%)", _m(st_["q3"])), ("Maximum", _m(st_["max"])),
        ("IQR", _m(st_["iqr"])), ("Skewness", "—" if st_["skewness"] is None else f"{st_['skewness']:.3f}"),
        ("Kurtosis", "—" if st_["kurtosis"] is None else f"{st_['kurtosis']:.3f}"),
        ("Coefficient of variation", "—" if st_["cv_pct"] is None else f"{st_['cv_pct']:.1f}%"),
        ("IQR outlier fences", f"{_m(lo)} – {_m(hi)}"), ("Outliers found", f"{len(outliers):,}"),
    ], columns=["Statistic", "Monthly salary"])
    dstats = an.department_stats(df).rename(columns={
        "department": "Department", "employees": "Employees", "mean": "Mean", "median": "Median", "std": "Std Dev",
        "min": "Min", "q1": "Q1", "q3": "Q3", "max": "Max", "iqr": "IQR"})
    miss = an.missing_values(df.drop(columns=["full_name"]))
    corr = an.correlation_matrix(df)
    tables = [("Descriptive statistics", stats_table), ("Department comparison", dstats),
              ("Missing values", miss.rename(columns={"column": "Column", "missing": "Missing", "missing_pct": "Missing %"}))]
    notes = []
    if not corr.empty:
        r = corr.loc["monthly_salary", "tenure_years"]
        notes.append(f"Pearson correlation between monthly salary and tenure: r = {r:.3f}.")
    if not outliers.empty:
        o = outliers[["employee_code", "department", "designation", "monthly_salary", "outlier_type"]].rename(columns={
            "employee_code": "Employee ID", "department": "Department", "designation": "Designation",
            "monthly_salary": "Monthly Salary", "outlier_type": "Type"})
        tables.append(("IQR outliers", o))
    return Report(
        title="Exploratory Data Analysis Report",
        subtitle="Statistical profile of monthly salaries",
        meta=_meta(user, statuses),
        kpis={"Records": f"{len(df):,}", "Mean": _m(st_["mean"]), "Median": _m(st_["median"]),
              "Std dev": _m(st_["std"]), "Outliers": f"{len(outliers):,}"},
        tables=tables, notes=notes,
        money_columns={"Mean", "Median", "Std Dev", "Min", "Q1", "Q3", "Max", "IQR", "Monthly Salary"},
        pct_columns={"Missing %"},
    )


